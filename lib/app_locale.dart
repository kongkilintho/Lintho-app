import 'package:flutter/material.dart';
import 'package:shared_preferences/shared_preferences.dart';

enum AppLang { lo, en, th, zh }

class AppLocale extends ChangeNotifier {
  static final AppLocale _instance = AppLocale._();
  static AppLocale get instance => _instance;
  AppLocale._();

  static const _prefKey = 'app_lang';

  AppLang _lang = AppLang.lo;
  AppLang get lang => _lang;

  // ✅ ໂຫຼດພາສາທີ່ບັນທຶກໄວ້ — ເອີ້ນກ່ອນ runApp()
  static Future<void> loadSaved() async {
    final prefs  = await SharedPreferences.getInstance();
    final saved  = prefs.getString(_prefKey);
    if (saved != null) {
      _instance._lang = AppLang.values.firstWhere(
        (l) => l.name == saved,
        orElse: () => AppLang.lo,
      );
    }
  }

  void setLang(AppLang lang) {
    _lang = lang;
    notifyListeners();
    SharedPreferences.getInstance()
        .then((prefs) => prefs.setString(_prefKey, lang.name));
  }

  String get(String key) => _strings[_lang]?[key] ?? _strings[AppLang.lo]![key] ?? key;
}

